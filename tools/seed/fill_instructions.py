"""Наполнение раздела «Инструкции» через настоящий API — тем же путём, которым
пойдёт администратор. Идемпотентно: материал с тем же заголовком обновляется,
а не дублируется."""
import json
import os
import sys
import urllib.request
import uuid

BASE = "http://localhost:8080"


def req(method, path, token=None, data=None, files=None):
    url = BASE + path
    headers = {}
    if token:
        headers["Authorization"] = "Bearer " + token
    if files:
        boundary = uuid.uuid4().hex
        name, content, ctype = files
        body = b"".join([
            f"--{boundary}\r\n".encode(),
            f'Content-Disposition: form-data; name="file"; filename="{name}"\r\n'.encode(),
            f"Content-Type: {ctype}\r\n\r\n".encode(),
            content, b"\r\n", f"--{boundary}--\r\n".encode(),
        ])
        headers["Content-Type"] = f"multipart/form-data; boundary={boundary}"
    elif data is not None:
        body = json.dumps(data, ensure_ascii=False).encode()
        headers["Content-Type"] = "application/json"
    else:
        body = None
    r = urllib.request.Request(url, data=body, headers=headers, method=method)
    with urllib.request.urlopen(r) as resp:
        raw = resp.read()
        return json.loads(raw) if raw else None


def login(u, p):
    body = f"username={u}&password={p}".encode()
    r = urllib.request.Request(BASE + "/auth/login", data=body, method="POST",
                               headers={"Content-Type": "application/x-www-form-urlencoded"})
    with urllib.request.urlopen(r) as resp:
        return json.load(resp)["access_token"]


