#!/usr/bin/env python3
"""Дописывает в .docx-руководства разделы функционала, вышедшего после 31.07.2026.

Волны C–F и рекомендательная система (витрины, обращения, личный кабинет, папки
дашбордов, аномалии, подсказки виджетов/метрик, ретенция в UI, отчёт активности)
появились уже ПОСЛЕ последней сборки документов. Полная перегенерация всех пяти
.docx с нуля здесь не нужна: скрипт вставляет новые главы в существующие файлы,
сохраняя оформление (шрифты/цвета/подписи «Рис. N»), нумерацию продолжает и
сдвигает номер последней главы.

    python3 prepare_data.py         # временные данные для съёмки
    node shoot_sections.js          # скриншоты → shots/
    python3 append_sections.py      # вставка глав в docs/*.docx
    python3 prepare_data.py --cleanup

Идемпотентность: если раздел с таким заголовком уже есть, файл пропускается.
"""
from __future__ import annotations

import copy
import re
import sys
from pathlib import Path

import docx
from docx.shared import Emu, Inches, Pt, RGBColor

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs"
SHOTS = Path(__file__).resolve().parent / "shots"

IMG_W = Inches(6.38)          # как у существующих иллюстраций
C_TEXT = RGBColor(0x2C, 0x2A, 0x29)
C_H1 = RGBColor(0xE0, 0x4E, 0x39)
C_CAP = RGBColor(0x6B, 0x62, 0x5C)


class Builder:
    """Собирает абзацы в конце документа, затем переносит их перед якорем.

    Стили берутся ОБРАЗЦАМИ из самого документа: в этих .docx заголовки
    ссылаются на латентные стили Word, которых нет в styles.xml, поэтому
    `add_paragraph(style="Heading 1")` падает с KeyError. Копируем свойства
    абзаца (pPr) у существующего заголовка — заодно сохраняются отступы.
    """

    def __init__(self, doc):
        self.doc = doc
        self.made = []
        self.fig = self._last_figure_no(doc)
        self.samples = self._collect_samples(doc)

    @staticmethod
    def _collect_samples(doc) -> dict:
        out: dict = {}
        for par in doc.paragraphs:
            name = par.style.name if par.style else "Normal"
            if name not in out and par.text.strip():
                out[name] = par
        return out

    def _styled(self, sample_name):
        p = self.doc.add_paragraph()
        self.made.append(p)
        src = self.samples.get(sample_name)
        if src is not None and src._p.pPr is not None:
            p._p.insert(0, copy.deepcopy(src._p.pPr))
        return p

    @staticmethod
    def _last_figure_no(doc) -> int:
        n = 0
        for p in doc.paragraphs:
            m = re.match(r"\s*Рис\.\s*(\d+)", p.text)
            if m:
                n = max(n, int(m.group(1)))
        return n

    def _p(self):
        p = self.doc.add_paragraph()
        self.made.append(p)
        return p

    def h1(self, text):
        p = self._styled("Heading 1")
        r = p.add_run(text); r.bold = True; r.font.size = Pt(16); r.font.color.rgb = C_H1
        return p

    def h2(self, text):
        p = self._styled("Heading 2")
        r = p.add_run(text); r.bold = True; r.font.size = Pt(13); r.font.color.rgb = C_TEXT
        return p

    def body(self, *parts):
        """parts: строки или кортежи (текст, bold)."""
        p = self._p()
        for part in parts:
            text, bold = part if isinstance(part, tuple) else (part, False)
            r = p.add_run(text); r.bold = bold; r.font.size = Pt(11); r.font.color.rgb = C_TEXT
        return p

    def bullet(self, *parts):
        p = self._styled("List Paragraph")
        for part in parts:
            text, bold = part if isinstance(part, tuple) else (part, False)
            r = p.add_run(text); r.bold = bold; r.font.size = Pt(11); r.font.color.rgb = C_TEXT
        return p

    def pic(self, shot_name, caption):
        path = SHOTS / f"{shot_name}.png"
        if not path.exists():
            raise SystemExit(f"нет скриншота {path} — сначала `node shoot_sections.js`")
        p = self._p()
        p.add_run().add_picture(str(path), width=IMG_W)
        self.fig += 1
        cap = self._p()
        r = cap.add_run(f"Рис. {self.fig}. {caption}")
        r.italic = True; r.font.size = Pt(9); r.font.color.rgb = C_CAP
        return p

    def move_before(self, anchor_par):
        """Переносит собранные абзацы перед якорным абзацем, сохраняя порядок."""
        for p in self.made:
            anchor_par._p.addprevious(p._p)


def find_heading(doc, prefix):
    for p in doc.paragraphs:
        if p.style and p.style.name.startswith("Heading") and p.text.strip().startswith(prefix):
            return p
    return None


def renumber(par, new_text):
    """Меняет текст заголовка, сохраняя оформление первого run."""
    if not par.runs:
        return
    par.runs[0].text = new_text
    for r in par.runs[1:]:
        r.text = ""


def already_done(doc, marker) -> bool:
    return any(marker in p.text for p in doc.paragraphs)


