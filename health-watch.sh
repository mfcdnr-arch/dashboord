#!/usr/bin/env bash
# Сторож доступности системы: единственный сигнал, который уходит НАРУЖУ.
#
# Зачем это на ХОСТЕ. Всё, что система сообщает о своём состоянии, она пишет
# ВНУТРЬ себя: уведомления в колокольчик, «Здоровье системы», журнал починок.
# Пока она работает, этого хватает. Но ровно в том случае, ради которого сигнал
# и нужен — API не отвечает, веб-прокси лёг, кончилось место, встал Postgres —
# сообщать оказывается некому и некуда: экран, на котором было бы видно
# сообщение, и есть то, что не открывается. Узнают, когда кто-то попробует
# войти, то есть в худший момент и от постороннего человека.
#
# Сторож воркера (worker-guard.sh) эту дыру не закрывает: он проверяет ОДИН
# контейнер и пишет результат туда же, внутрь системы.
#
# Что он делает: раз в несколько минут спрашивает /health снаружи — тем же
# путём, которым ходит человек, через веб-прокси и TLS, — и при отказе
# оставляет след там, где дежурный его увидит БЕЗ системы:
#   • ops-triggers/health.state — человеческим текстом, что и с каких пор;
#   • ops-triggers/health.log   — история переходов (не каждая проверка);
#   • системный журнал (logger → journalctl -t dashbord-health) — канал,
#     который администратор на сервере и так читает, и который переживает
#     падение чего угодно в самой системе.
#
# Почтового канала и вебхука здесь НЕТ намеренно: это новая инфраструктура для
# закрытого контура (SMTP-релей, адреса, доступ наружу) — решение эксплуатации,
# а не правка кода. Когда он появится, слать письмо будет ровно отсюда: место
# для этого — функция notify() ниже.
#
# Запуск: из ops-trigger-watch.sh, который хостовой таймер и так гонит раз в
# минуту. Отдельный таймер заводить НЕ стали намеренно: на уже развёрнутых
# серверах его пришлось бы ставить руками (`sudo ./backup-schedule.sh install`),
# и на боевом он появился бы ровно тогда, когда про это вспомнят. Так же
# поступили со сторожем воркера 15.09 — он заработал в бою сам, с обычной
# поставкой. Частоту задаёт сам скрипт (HEALTH_INTERVAL), а не тот, кто его
# зовёт: раз в минуту проверять незачем, а трёх осечек подряд при минутном шаге
# хватило бы, чтобы каждый деплой поднимал ложную тревогу.
set -euo pipefail
cd "$(dirname "$0")"
REPO="$(pwd)"
. ./http-lib.sh

env_get() { { grep -E "^$1=" .env.prod 2>/dev/null | cut -d= -f2- | tail -1; } || true; }

# Адрес проверки. По умолчанию — снаружи, через веб-прокси: именно так систему
# видит человек. Проверять API по внутреннему адресу значило бы пропустить
# самый частый случай отказа — лежит прокси, а API при этом жив.
HTTPS_PORT="$(env_get HTTPS_PORT)"; HTTPS_PORT="${HTTPS_PORT:-8443}"
WEB_PORT="$(env_get WEB_PORT)"; WEB_PORT="${WEB_PORT:-8080}"
if [ -n "$(env_get TLS_SAN)$(env_get TLS_CN)" ] || [ -d certs ]; then
  DEFAULT_URL="https://127.0.0.1:${HTTPS_PORT}/health"
else
  DEFAULT_URL="http://127.0.0.1:${WEB_PORT}/health"
fi
URL="${HEALTH_URL:-$DEFAULT_URL}"
TIMEOUT="${HEALTH_TIMEOUT:-10}"

# 🔴 Тревога объявляется не с первой осечки. Сеть моргает, прокси
# перезапускается при деплое, сервер занят — одиночный отказ это не авария.
# Сигнал, который поднимает дежурного зря, перестают читать, и тогда он не
# сработает в настоящий раз. Три подряд при шаге в 5 минут — это примерно
# четверть часа непрерывной недоступности, которую уже нельзя списать на рябь.
FAILS_TO_ALARM="${HEALTH_FAILS_TO_ALARM:-3}"
# Шаг проверки. Зовут нас раз в минуту, а спрашиваем раз в пять — три осечки
# подряд это примерно четверть часа недоступности.
INTERVAL="${HEALTH_INTERVAL:-300}"

TRIGGER_DIR="${OPS_TRIGGER_DIR:-$REPO/ops-triggers}"
STATE_FILE="$TRIGGER_DIR/health.state"
COUNT_FILE="$TRIGGER_DIR/health.fails"
LOG_FILE="$TRIGGER_DIR/health.log"
TAG="${HEALTH_SYSLOG_TAG:-dashbord-health}"
LAST_FILE="$TRIGGER_DIR/health.last"
# Пауза на время обслуживания: deploy.sh кладёт этот файл на время обновления и
# убирает после. Без неё КАЖДОЕ обновление поднимало бы тревогу — система на
# это время и правда недоступна, но дежурному сообщать нечего, а ложный сигнал
# ровно так и обесценивается.
OFF_FILE="$TRIGGER_DIR/health-watch.off"

mkdir -p "$TRIGGER_DIR"
iso() { date -u +%Y-%m-%dT%H:%M:%SZ; }

# Единственное место, куда добавляется внешний канал (письмо, вебхук, СМС),
# когда заказчик решит его завести. Всё остальное — определение состояния.
notify() {  # $1 level (alarm|recovery), $2 текст
  # `logger` есть в любой системной сборке; -p отправляет в системный журнал с
  # понятным приоритетом, чтобы строка нашлась обычным `journalctl -p err`.
  if command -v logger >/dev/null 2>&1; then
    case "$1" in
      alarm)    logger -t "$TAG" -p daemon.err  "$2" || true ;;
      recovery) logger -t "$TAG" -p daemon.notice "$2" || true ;;
    esac
  fi
  printf '%s\t%s\t%s\n' "$(iso)" "$1" "$2" >> "$LOG_FILE"
}

read_prev() { [ -f "$STATE_FILE" ] && head -1 "$STATE_FILE" || echo "unknown"; }
write_state() {  # $1 state, $2 текст
  { echo "$1"; echo "$(iso)"; echo "$2"; } > "$STATE_FILE"
}

# --- когда вообще проверять ------------------------------------------------
if [ -f "$OFF_FILE" ]; then
  # Счётчик осечек сбрасываем: после обслуживания отсчёт начинается заново,
  # иначе первая же проверка после деплоя добила бы порог «накопленным» отказом.
  echo 0 > "$COUNT_FILE"
  exit 0
fi

NOW="$(date +%s)"
if [ -f "$LAST_FILE" ]; then
  LAST="$(tr -dc '0-9' < "$LAST_FILE" 2>/dev/null || echo 0)"
  [ $(( NOW - ${LAST:-0} )) -lt "$INTERVAL" ] && exit 0
fi
echo "$NOW" > "$LAST_FILE"

# --- сама проверка ---------------------------------------------------------
if ! http_client_available; then
  # Ни curl, ни python3 — проверять нечем. Молчать нельзя: иначе «сторож
  # работает» неотличимо от «сторож ничего не может», а это ровно тот тихий
  # отказ, против которого он заведён (та же ловушка, что была с flock).
  notify alarm "Сторож доступности не может работать: на сервере нет ни curl, ни python3"
  write_state "broken" "Нечем выполнить HTTP-проверку"
  exit 0
fi

CODE="$(http_code "$URL" "$TIMEOUT")"
BODY=""
[ "$CODE" = "200" ] && BODY="$(http_body "$URL" "$TIMEOUT" 2>/dev/null || true)"

# Исходов ЧЕТЫРЕ, а не два, и различать их надо: за каждым стоит своя починка.
# Свалить их в общее «система недоступна» значило бы послать дежурного не туда —
# чинить Postgres там, где сломана маршрутизация.
#
# 🔴 Четвёртый исход найден живой проверкой, а не придуман: на порту оказался
# чужой веб-сервер, и он отдал на /health обычную HTML-страницу с кодом 200.
# В бою это ровно тот случай, когда запрос не доходит до API и проваливается в
# SPA-fallback nginx (см. журнал 10.08: «200 на защищённый маршрут — повод
# посмотреть nginx», и 502 после обновления, когда прокси держал старый адрес).
# Первая версия называла это «база данных недоступна» — правдоподобно и неверно.
if [ "$CODE" != "200" ]; then
  STATE="down"
  case "$CODE" in
    000) DETAIL="сервер не отвечает вовсе (нет соединения с $URL)" ;;
    50*) DETAIL="веб-прокси отвечает ошибкой $CODE — похоже, приложение за ним не поднялось" ;;
    5*)  DETAIL="приложение отвечает ошибкой $CODE" ;;
    *)   DETAIL="неожиданный ответ $CODE" ;;
  esac
elif ! printf '%s' "$BODY" | grep -q '"db"[[:space:]]*:'; then
  STATE="wrong"
  DETAIL="на /health отвечает не приложение (ответ без поля db) — проверьте маршруты веб-прокси"
elif printf '%s' "$BODY" | grep -q '"db"[[:space:]]*:[[:space:]]*"ok"'; then
  STATE="ok"
  DETAIL="система отвечает"
else
  STATE="degraded"
  DETAIL="приложение отвечает, но база данных недоступна"
fi

PREV="$(read_prev)"
FAILS=0
[ -f "$COUNT_FILE" ] && FAILS="$(tr -dc '0-9' < "$COUNT_FILE" 2>/dev/null || echo 0)"
FAILS="${FAILS:-0}"

if [ "$STATE" = "ok" ]; then
  echo 0 > "$COUNT_FILE"
  write_state "ok" "$DETAIL"
  # 🔴 О восстановлении сообщаем ТОЛЬКО если до этого объявляли тревогу. Иначе
  # красная отметка висела бы вечно и читалась как незакрытая авария, а зелёная
  # строка каждые пять минут превратила бы журнал в шум, в котором тревогу и
  # не заметишь.
  [ "$PREV" = "alarm" ] && notify recovery "Система снова доступна ($URL)"
  exit 0
fi

FAILS=$(( FAILS + 1 ))
echo "$FAILS" > "$COUNT_FILE"

if [ "$FAILS" -lt "$FAILS_TO_ALARM" ]; then
  # Осечка, но ещё не авария: состояние записываем (чтобы было видно, что
  # сторож не спит и что-то заметил), наружу не кричим.
  write_state "$STATE" "$DETAIL — осечка $FAILS из $FAILS_TO_ALARM, тревога ещё не объявлена"
  exit 0
fi

# Порог перейдён. Повторно не кричим: тревога объявляется на ПЕРЕХОДЕ, иначе
# каждые пять минут приходило бы одно и то же, и в этом потоке потерялось бы
# всё остальное.
if [ "$PREV" != "alarm" ]; then
  notify alarm "Система недоступна: $DETAIL. Проверок подряд: $FAILS. Адрес: $URL"
fi
write_state "alarm" "$DETAIL (неудачных проверок подряд: $FAILS)"
