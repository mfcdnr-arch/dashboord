-- Список документов папки сортируется по ОТЧЁТНОЙ дате, а не по времени загрузки.
--
-- Заказчик загружает недельные формы не по порядку (сначала августовскую, потом
-- апрельскую), и список выглядел вперемешку: 29.07, 15.04, 29.04, 16.07…
-- Отчётная дата — то, чем эти файлы различаются по смыслу, по ней и сортируем.
--
-- Индекс повторяет порядок сортировки (folder_id, reporting_period_start desc),
-- иначе папка с сотнями форм каждый раз сортируется в памяти. NULLS LAST — чтобы
-- документы без отчётной даты не всплывали над датированными.
create index if not exists ix_documents_folder_period
  on documents (folder_id, reporting_period_start desc nulls last, created_at desc);
