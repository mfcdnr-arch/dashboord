-- =========================================================
-- 034 · Объединённые ячейки и область данных в распознанной таблице
--
-- Зачем: на реальном отчёте заказчика («приложение к письму» с баннером во всю
-- ширину и многоэтажной шапкой) разметка разваливалась. Значение объединения
-- размножалось по всем столбцам, из-за чего все 16 столбцов получали имя
-- «ИНФОРМАЦИЯ», а шапкой считался текст письма. Чинится это только если знать
-- ГЕОМЕТРИЮ листа, а её нигде не хранили.
--
--   * merges     — диапазоны объединений [[r1,c1,r2,c2], ...], нумерация с нуля,
--                  границы включительно. Значение лежит в левой верхней клетке;
--                  предпросмотр рисуется rowspan/colspan, анализ разворачивает
--                  диапазон (parsers.fill_merges).
--   * data_rect  — выбранная пользователем область данных [r1,c1,r2,c2] (NULL —
--                  пока не выбрана, берётся вся сетка). Отделяет таблицу от
--                  шапки письма.
--
-- Данные, распознанные ДО этой миграции, остаются валидными: пустой merges
-- означает «объединений нет», и всё работает как раньше.
-- =========================================================

alter table extracted_tables
    add column if not exists merges jsonb not null default '[]'::jsonb,
    add column if not exists data_rect jsonb;

comment on column extracted_tables.merges is
    'Диапазоны объединённых ячеек [[r1,c1,r2,c2], ...], 0-based, границы включительно.';
comment on column extracted_tables.data_rect is
    'Область данных [r1,c1,r2,c2], выбранная пользователем. NULL — вся сетка.';
