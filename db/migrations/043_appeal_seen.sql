-- Кто и когда ПЕРВЫМ открыл обращение со стороны администрации.
--
-- Две разные беды закрываются одной отметкой:
--
--  1. Автор не видел, что его жалобу вообще заметили: до первого ответа
--     обращение выглядело так же, как в момент отправки, — то есть как будто
--     ушло в пустоту. Теперь ему видно «просмотрено 17.08 в 10:40» и приходит
--     одно уведомление (именно одно — на ПЕРВЫЙ просмотр; сообщать о каждом
--     открытии карточки значило бы превратить ленту в шум).
--
--  2. Администратор не видел, сколько обращение ждёт. Отметка даёт честную
--     границу: «ждёт ответа N ч» считается от создания, а «взято в работу» —
--     от первого просмотра, и одно не выдаётся за другое.
alter table appeals add column if not exists first_seen_at timestamptz;
alter table appeals add column if not exists first_seen_by uuid references users(id) on delete set null;

-- Потолок на новые обращения (10 в час) считается по автору за последний час.
create index if not exists ix_appeals_user_created on appeals (user_id, created_at desc);
