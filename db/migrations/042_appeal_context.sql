-- Обращения, отправленные кнопкой «сообщить о проблеме» с виджета, несут
-- контекст: с какого дашборда, страницы и виджета пришла жалоба.
--
-- Зачем отдельная колонка, а не только текст сообщения: по тексту администратор
-- ПРОЧИТАЕТ, где проблема, но не сможет туда ПЕРЕЙТИ. Ссылки в jsonb дают в
-- карточке обращения кнопку «Открыть дашборд» — иначе разбор жалобы начинается
-- с поиска отчёта по названию среди десятков.
--
-- Колонка необязательная: обычные обращения (из кабинета, от заблокированного
-- аккаунта) контекста не имеют и не должны его иметь.
alter table appeals add column if not exists context jsonb;

-- Повторная жалоба на ТОТ ЖЕ виджет дописывается в уже открытое обращение, а не
-- заводит второе (иначе очередь администратора забивается дублями одной беды).
-- Поиск идёт по виджету среди незакрытых обращений автора.
create index if not exists ix_appeals_context_widget
    on appeals ((context ->> 'widget_id'))
    where context is not null;
