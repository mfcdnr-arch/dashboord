-- 038. Авто-конвейер папки, кусок 2: файл сам доходит до состояния «данные подготовлены».
--
-- Что меняется по смыслу: распознавание больше не ждёт отдельного нажатия, а
-- сразу после него система сверяет структуру файла с шаблоном объекта и
-- запоминает вердикт. Человек открывает папку и видит по каждому файлу, готов
-- он к выпуску или требует внимания, — вместо того чтобы заходить в каждый.
--
-- `headers` в шаблоне нужны, чтобы объяснить РАСХОЖДЕНИЕ словами («добавилась
-- графа „Записались"»). Одного отпечатка для этого мало: он хеш, по нему видно
-- только «не совпало», а человеку нужно знать, что именно изменилось в бланке.

alter table object_layout_templates
    add column if not exists headers jsonb not null default '[]'::jsonb;

-- Вердикт сверки со шаблоном, посчитанный воркером сразу после распознавания.
-- null — сверка не проводилась (старые задания, ошибка распознавания).
alter table extraction_jobs
    add column if not exists template_match text,
    add column if not exists template_note  text;

comment on column extraction_jobs.template_match is
    'exact — разметку прошлого выпуска можно подставить; structure_differs — форма изменилась; none — шаблона ещё нет';
