-- 039. Авто-конвейер, кусок 4: ручное управление автоматикой.
--
-- «Автообновление» в системе означает три РАЗНЫЕ вещи, и человек должен
-- управлять ими раздельно, иначе один тумблер обещал бы непонятно что:
--   1) цифры в виджетах — обновляются всегда (виджет читает последний
--      неотменённый выпуск), тумблера нет и не нужно: дашборд, который
--      показывает устаревшие числа молча, опаснее любого автообновления;
--   2) подготовка выпуска из нового файла — `folders.auto_prepare`;
--   3) подсказки о показателях, которых нет на дашборде — `dashboards.suggest_new_fields`.
--
-- Обе галочки включены по умолчанию: подготовка и подсказка ничего не
-- публикуют и ничего не меняют без человека.

alter table folders
    add column if not exists auto_prepare boolean not null default true;

alter table dashboards
    add column if not exists suggest_new_fields boolean not null default true;

comment on column folders.auto_prepare is
    'Готовить выпуск автоматически: распознавать новый файл и подставлять разметку прошлого выпуска';
comment on column dashboards.suggest_new_fields is
    'Подсказывать, когда в данных появились показатели, которых нет на дашборде';
