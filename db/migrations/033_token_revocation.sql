-- 033: Отзыв ранее выданных JWT при смене/сбросе пароля.
--
-- До этого токен жил до истечения срока (JWT_EXPIRE_MINUTES, по умолчанию 12 ч)
-- независимо от смены пароля: при компрометации приходилось блокировать учётку
-- (блокировка действует мгновенно — is_active проверяется на каждом запросе).
-- Теперь в токен пишется `iat`, а здесь фиксируется момент последней смены
-- пароля: токены, выданные ДО неё, считаются недействительными.
--
-- Существующим пользователям ставим NULL (проверка не применяется к токенам,
-- выданным до внедрения) — иначе одномоментно разлогинились бы все.
alter table users add column if not exists password_changed_at timestamptz;

comment on column users.password_changed_at is
    'Момент последней смены/сброса пароля. JWT с iat < этого значения отвергается.';
