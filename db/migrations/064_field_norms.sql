-- 064 · Порог показателя (норма), один на графу формы
--
-- До сих пор пороги жили в каждом виджете отдельно (config.alerts): «время
-- ожидания больше 30 минут — плохо» пришлось бы вписывать в карточку, в
-- рейтинг, в таблицу и в динамику по отдельности, и при первой же правке они
-- разошлись бы. Порог — свойство ПОКАЗАТЕЛЯ, а не картинки, поэтому живёт у
-- графы формы. Его применяют все виджеты по этой графе и блок «На что
-- посмотреть»; правка в одном месте пересчитывает всё.
--
-- norm = {"warn": число | null, "danger": число | null, "direction": "lower" | "higher",
--         "updated_at": ..., "updated_by": ...}
--   direction = lower  — чем меньше, тем лучше (время ожидания): проблема — от «danger» и выше;
--   direction = higher — чем больше, тем лучше: проблема — от «danger» и ниже.
-- Значения — в единице графы (у длительности — в минутах).
--
-- Идемпотентно.
-- =========================================================

alter table canonical_fields add column if not exists norm jsonb;
