-- 040. Мастер авто-сборки, этап 4: выбор запоминается.
--
-- Мастер каждый раз открывался «как в первый раз»: человек снова снимал
-- ненужные графы, снова выбирал вид каждого показателя, снова отмечал недели.
-- При недельной форме это повторяется буквально каждую неделю.
--
-- Храним последний выбор на ОБЪЕКТЕ (объект = одна форма, решение заказчика):
-- набор данных → показатели, блоки, виды, недели, расчётные показатели.
-- Это подсказка, а не закон: мастер открывается с прошлым выбором, но человек
-- меняет его как хочет, и сохраняется то, чем он воспользовался в итоге.

alter table objects
    add column if not exists build_preferences jsonb;

comment on column objects.build_preferences is
    'Последний выбор в мастере авто-сборки: чем открывать мастер в следующий раз';
