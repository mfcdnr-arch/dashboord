-- Авто-выпуск данных перестаёт быть невидимым.
--
-- С 18.08 файл, в точности повторяющий прошлый отчёт, выпускается без участия
-- человека. Полезно, но до сих пор об этом нигде не было сказано:
--
--  1. В `dataset_releases` не было ни одного признака, отличающего выпуск
--     автомата от выпуска человека. Автором пишется тот, кто ЗАГРУЗИЛ файл
--     (решение верное — в журнале должен быть виден живой человек), но из-за
--     этого выпуск выглядит так, будто модератор нажал кнопку, хотя он её не
--     нажимал. Отличить постфактум было нечем — ни отчётом, ни запросом.
--
--  2. Папка не могла отказаться. Авто-выпуск висел на том же тумблере
--     `auto_prepare`, что и авто-распознавание, а это два разных решения:
--     «готовь без меня» не означает «выпускай без меня». Отдельная галочка
--     даёт и путь отката — выключается мышью, без правки кода.
--     Значение по умолчанию `true`: так система ведёт себя со вчерашнего дня,
--     и молча отключать уже работающее поведение миграцией нельзя.
alter table dataset_releases add column if not exists auto_released boolean not null default false;
alter table folders add column if not exists auto_release boolean not null default true;
