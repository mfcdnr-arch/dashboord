-- Потолок автоперезапусков воркера — в «Настройки», а не в код.
--
-- Сторож (worker-guard.sh) поднимает молчащий воркер, но не бесконечно: иначе
-- циклически падающий воркер перезапускался бы вечно и автоматика прятала бы
-- причину падения. Сколько попыток в час допустимо — решение эксплуатации, а
-- не разработки, поэтому живёт рядом с остальными порогами и правится мышью.
--
-- Значение 3 совпадает с прежним умолчанием в скрипте: у тех, кто ничего не
-- трогал, поведение не меняется.
alter table system_settings
    add column if not exists worker_restart_max_per_hour int not null default 3;
