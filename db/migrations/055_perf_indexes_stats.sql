-- Производительность: недостающий индекс и пороги автоанализа для таблиц,
-- которые растут ПАЧКАМИ, а не равномерным потоком мелких правок.
--
-- Замеры на живых данных (1,2 млн значений, 58 тыс. колонок):
--
-- (1) Колонки распознанной таблицы искались последовательным сканированием:
--     3 255 буферов (~25 МБ) на каждый запрос, а он идёт при каждом открытии
--     разметки файла. С ростом числа загруженных файлов дорожает линейно.
create index if not exists ix_extracted_columns_table
    on extracted_columns (extracted_table_id, column_index);

-- (2) Статистика отставала. Умолчание автоанализа — «10 % таблицы + 50 строк»;
--     для dataset_values это 122 034 изменения, а один отчёт РЦО добавляет
--     ~21 600 значений. То есть статистика обновлялась примерно раз в ШЕСТЬ
--     отчётов, и между ними планировщик строил планы по устаревшим данным.
--     Понижаем порог: 1 % + 2 000 ≈ 14 000 изменений, то есть чаще одного
--     отчёта. Вакуум тоже чаще умолчания (0.2) — таблица только растёт.
alter table dataset_values set (
    autovacuum_analyze_scale_factor = 0.01,
    autovacuum_analyze_threshold = 2000,
    autovacuum_vacuum_scale_factor = 0.05
);

-- Журнал действий растёт постоянно и читается отчётами с фильтрами по дате и
-- сущности — там плохой план особенно заметен.
alter table audit_log set (
    autovacuum_analyze_scale_factor = 0.02,
    autovacuum_analyze_threshold = 2000,
    autovacuum_vacuum_scale_factor = 0.1
);

-- Колонки приходят пачкой на каждый распознанный файл.
alter table extracted_columns set (
    autovacuum_analyze_scale_factor = 0.05,
    autovacuum_analyze_threshold = 1000
);

-- Разовый сбор статистики: новые пороги подействуют только со следующего
-- накопления изменений, а плохой план мешает уже сейчас. Новому индексу
-- статистика нужна тем более — без неё планировщик о нём не узнает.
analyze extracted_columns;
analyze dataset_values;
analyze audit_log;
