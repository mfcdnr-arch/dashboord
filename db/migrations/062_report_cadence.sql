-- 062: ритм поступления отчёта — задаётся человеком (11.10.2026).
--
-- Ритм формы система выводит из истории (`infer_cadence`), и ей нужно минимум
-- четыре отчёта: на двух-трёх «ритм» был бы случайностью. Значит, у новой
-- формы напоминание «отчёт не поступил» молчит первый месяц — у книги
-- Минэкономразвития (каждую неделю, первый отчёт 06.10.2026) оно заработало бы
-- только к ноябрю. Если ритм известен заранее, человек задаёт его на объекте,
-- и он действует с первого отчёта; пусто — как прежде, по истории.
alter table objects add column if not exists report_cadence_days int
    check (report_cadence_days is null or report_cadence_days between 1 and 366);

comment on column objects.report_cadence_days is
    'Как часто приходит отчёт, дней (задано человеком); пусто — определяется по истории выпусков';
