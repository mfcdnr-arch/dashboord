-- Комментарий к КОНКРЕТНОЙ ЦИФРЕ, а не ко всему отчёту (п. 8).
--
-- До этого обсуждение привязывалось только к дашборду: замечание «эта цифра
-- занижена, отделение переезжало» приходилось начинать с объяснения, о какой
-- из тридцати цифр речь.
--
-- Три колонки, и вторая из них — главная:
--
--   widget_id — о каком виджете речь. NULL остаётся у прежних комментариев ко
--     всему отчёту, и такой способ никуда не девается: замечание «дашборд
--     неудобный» не относится ни к одной цифре.
--
--   period — ЗА КАКУЮ ОТЧЁТНУЮ ДАТУ была цифра в момент, когда её обсуждали.
--     Без этого комментарий об августовском числе через неделю висел бы рядом
--     с сентябрьским и вводил бы в заблуждение молча: виджет показывает
--     последний выпуск, а текст остаётся прежним.
--
--   row_label — если человек провалился в строку (район, отделение), речь о
--     ЕЁ цифре, а не об итоге.
--
-- widget_id удаляется каскадом вместе с виджетом: комментарий про «эту цифру»
-- на виджете, которого больше нет, указывает в никуда — в отличие от слепка
-- архива или записи о входе, он не содержит самих данных и ценности без
-- своего виджета не имеет.
alter table dashboard_comments
  add column if not exists widget_id uuid references widgets(id) on delete cascade,
  add column if not exists period date,
  add column if not exists row_label text;

-- Лента виджета читается по (widget_id, время) — отдельный индекс, потому что
-- существующий по (dashboard_id, created_at) для неё не годится.
create index if not exists ix_dashboard_comments_widget
  on dashboard_comments (widget_id, created_at desc)
  where widget_id is not null;
