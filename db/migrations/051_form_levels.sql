-- 051. Ступени формы: подтверждённая человеком иерархия рядом с разметкой.
--
-- Замысел заказчика: «делай общий дашборд, потом постепенно разбивай данные на
-- более мелкие показатели — по ведомствам, потом по услугам в этих ведомствах».
-- Распознавание (кусок 1) уже умеет ПРЕДЛОЖИТЬ ступени по именам граф; здесь
-- появляется дом для того, что человек подтвердил.
--
-- Живёт в шаблоне объекта, а не отдельной таблицей, по той же причине, по
-- которой там живёт разметка: объект = одна форма, и контракт «подтвердил раз —
-- дальше само» должен быть один. Пустой объект `{}` означает «ещё не
-- подтверждали» — тогда мастер показывает предложение.
--
-- Внутри лежит и ОТПЕЧАТОК, при котором иерархия подтверждалась. Он нужен
-- затем же, зачем отпечаток самой разметке: форма меняется, и подтверждение,
-- данное для прошлого бланка, к новому может не подходить. Не совпал —
-- показываем предложение заново, а не применяем устаревшее молча.
alter table object_layout_templates
    add column if not exists levels jsonb not null default '{}'::jsonb;

comment on column object_layout_templates.levels is
    'Подтверждённые человеком ступени формы: разделитель, имена уровней, отпечаток на момент подтверждения';
