"""Какая версия формулы показателя считается ДЕЙСТВУЮЩЕЙ.

Правило одно на всю систему и живёт здесь.

До 21.09.2026 оно было скопировано в тринадцать мест восьми модулей, причём в
ДВУХ несовпадающих редакциях: одна ставила черновик наравне со снятой с
эксплуатации версией (`… else 2`), другая — впереди неё (`… draft then 2 else
3`). Обе редакции соседствовали даже внутри одного файла (`metrics/service.py`:
каталог источников считал по первой, список значений — по второй), то есть на
вопрос «по какой формуле это число» модуль отвечал двумя способами сразу.

Сегодня расхождение не проявляется: `deprecated` проставляется ТОЛЬКО при
одобрении новой версии (`service.set_status`), поэтому рядом всегда есть
`approved`, который выигрывает в обеих редакциях, а `archived` не ставит
никто. Но обе опоры держатся на честном слове: стоит появиться переходу
«снять с эксплуатации, не одобряя замену» — и подсказка ⓘ начнёт называть
одну формулу, а виджет считать по другой. Молча.

Порядок: одобренная → проверенная → черновик → снятая → архивная.
Снятые и архивные НЕ исключаются вовсе, и это решение: показатель, у которого
не осталось ни одной живой версии, иначе перестал бы считаться вовсе, а
виджет ответил бы отказом вместо числа — «запрет без выхода», на который
проект уже наступал (10.08, самоодобрение). Вместо этого версия берётся, а её
состояние называется словами в подсказке ⓘ (`_explain._STATUS_RU`).
"""
from __future__ import annotations

# Порядок статусов; меняется вместе с _explain._STATUS_RU — там те же
# состояния объясняются человеку.
STATUS_RANK = ("approved", "validated", "draft", "deprecated")


def best_version_order(alias: str = "mv") -> str:
    """Кусок `order by` для выбора действующей версии формулы.

    alias — псевдоним таблицы metric_versions в запросе ("" если его нет).
    """
    p = f"{alias}." if alias else ""
    cases = " ".join(f"when '{s}' then {i}" for i, s in enumerate(STATUS_RANK))
    return f"case {p}status {cases} else {len(STATUS_RANK)} end, {p}version_no desc"
