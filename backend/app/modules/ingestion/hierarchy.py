"""Устройство формы: лежат ли в именах граф УРОВНИ.

Заказчик: «делай общий дашборд, потом постепенно разбивай данные на более
мелкие показатели — файл статистики: общие показатели, потом по ведомствам,
потом по услугам в этих ведомствах». Чтобы так разложить форму, систему надо
сперва научить видеть в ней ступени.

Сигнал — ИМЯ ГРАФЫ, а не устройство файла. У формы РЦО имена собраны из
сегментов через « · »:

    «Росреестр · Государственная регистрация прав … · Принято, ед.»
     └ ступень 1 ┘ └────────── ступень 2 ──────────┘ └── мера ──┘

Последний сегмент — это ЧТО измеряем (мера), ступени — всё, что до него.

🔴 Главная ловушка, ради которой модуль вообще устроен так, а не проще.
Разделитель « · » стоит и в РЦО, и в форме МАХ, но означает РАЗНОЕ:

    РЦО: «ведомство · услуга · мера»
    МАХ: «показатель · роль · разрез»   ← «Количество обращений · Факт · нарастающим итогом»

Наивное правило «разделитель = уровни» построило бы на МАХ лестницу, в которой
показатели притворяются ведомствами, а «План» и «Факт» — услугами. Выглядело бы
правдоподобно и было бы полностью неверным — тот же класс ошибки, что уже
ловили в сравнении подразделений (сопоставление по имени показателя).

Разделяющее правило: **если КАЖДЫЙ хвост имени опознан как разрез или роль —
это не уровни, а разрезы одного показателя.** Замер по всем 16 формам стенда
(766 граф) дал разрыв во всю шкалу, а не подобранный порог:

    РЦО ежедневный   4 хвоста, из них разрезов 0  → уровни
    Статистика ×12   5–11 хвостов, разрезов 0–2   → уровни
    МАХ              4 хвоста, из них разрезов 4  → разрезы показателя
    КПЭ, окна и часы разделителя нет вовсе        → плоская форма

Новых догадок правило не вводит: словарь ролей живёт в `data_suggestions` с
09.08, признак «хвост назвал единицу» — в `_aggregate.subject_with_measure`
с 08.09. Здесь они только собраны вместе.
"""
from __future__ import annotations

import re
from typing import Dict, List, Optional, Sequence

from ..dashboards._aggregate import is_total_column
from ..metrics.data_suggestions import _PLAN_RE, _clean
from ..metrics.describe import _plural

# Вердикт об устройстве формы.
KIND_HIERARCHY = "hierarchy"   # в именах граф лежат ступени
KIND_SLICES = "slices"         # один показатель в разрезах (МАХ)
KIND_FLAT = "flat"             # разделителя нет — плоская форма (КПЭ, окна)

# Разделители сегментов, встречающиеся в формах МФЦ. « · » — госформы РЦО и
# МАХ; «:» — «Статистика услуг» («Услуга 1: Принято»). Порядок задаёт
# приоритет: у формы, где есть оба, выигрывает первый.
SEPARATORS = (" · ", ":")

# Разрез показателя: «нарастающим итогом», «за отчётную неделю», «текущий
# месяц». Слова взяты из тех же форм, что разбирает `data_suggestions`.
_SLICE_RE = re.compile(r"нараст|за отч[ёе]т|недел|месяц|квартал|полугод|за год|итогом", re.I)

# Ступень признаётся, если она есть у такой доли граф. Порог не косметический:
# у РЦО пять граф имеют ЧЕТЫРЕ сегмента, но это не четвёртая ступень, а « · »
# внутри длинного названия услуги ФНС — 5 граф из 331 (1,5 %) отсекаются, а
# настоящая вторая ступень есть у 87 % и проходит с запасом.
LEVEL_PRESENCE = 2 / 3

# Доля объёма, ниже которой значение первой ступени без своей подступени
# считается одиноким и уходит в общий узел. Порог не подобран под красивый
# результат — он лежит в НАЙДЕННОМ разрыве: на всей истории РЦО (53 отчёта)
# у ОМС 4,85 % объёма, у следующего за ним 0,40 %, то есть разрыв в 12 раз, и
# 1 % отстоит от обеих сторон в 2,5–4,8 раза.
LONE_SHARE = 0.01

# Как назвать узел, в который сводятся одинокие значения.
LONE_NODE = "Отдельные услуги"

# Короткий список не группируем вовсе. Порог не выдуман: первый экран лестницы
# рисует «Ранжированный список», а он показывает 12 строк — если список в него
# и так помещается, группировка не даёт ничего, зато прячет часть формы. Найдено
# живой проверкой: у «Статистики услуг — ФНС» всего 6 услуг, и правило по
# объёму сворачивало ТРИ из них, то есть половину формы, в «Отдельные услуги».
GROUP_FROM_ROWS = 12


def is_slice_tail(tail: Optional[str]) -> bool:
    """Хвост имени — разрез или роль показателя, а не мера.

    Порядок проверок важен по смыслу: сперва разрез, потом единица. Хвост
    «нарастающим итогом, ед.» — это разрез, у которого вдобавок названа
    единица; проверь мы единицу первой, такая графа сошла бы за меру.
    """
    text = _clean(tail or "")
    if not text:
        return False
    if _SLICE_RE.search(text) or _PLAN_RE.search(text):
        return True
    # Единица («, ед.», «, чел.») или процент — форма назвала МЕРУ.
    return False


def split_segments(name: Optional[str], separator: str) -> List[str]:
    """Имя графы → сегменты. Пустые отбрасываются, сноски-звёздочки снимаются."""
    if not name:
        return []
    parts = [_clean(p) for p in name.split(separator)]
    return [p for p in parts if p]


def pick_separator(names: Sequence[str]) -> Optional[str]:
    """Разделитель формы — тот, что делит ИМЕНА чаще прочих.

    Считаем графы, а не вхождения: имя с пятью двоеточиями внутри текста не
    должно перевесить сорок имён с одним « · ».
    """
    best: Optional[str] = None
    best_count = 0
    for sep in SEPARATORS:
        count = sum(1 for n in names if len(split_segments(n, sep)) >= 2)
        if count > best_count:
            best, best_count = sep, count
    return best if best_count else None


def detect_levels(names: Sequence[str]) -> Dict:
    """Устройство формы по именам её граф.

    Возвращает вердикт, разделитель, ступени со списком значений и ПРИЧИНУ
    словами — её показывает мастер: «предложено» без объяснения человек
    подтверждать не станет, а молча угадывать нам запрещено решением заказчика.
    """
    clean_names = [n for n in (names or []) if _clean(n or "")]
    empty: Dict = {"kind": KIND_FLAT, "separator": None, "levels": [], "measures": [],
                   "fields_total": len(clean_names), "fields_with_separator": 0}

    sep = pick_separator(clean_names)
    if sep is None:
        return {**empty, "reason": "В именах граф нет разделителя — форма плоская, "
                                   "ступеней в ней не заложено."}

    segmented = [split_segments(n, sep) for n in clean_names]
    with_sep = [s for s in segmented if len(s) >= 2]
    total = len(with_sep)
    if not total:
        return {**empty, "reason": "В именах граф нет разделителя — форма плоская, "
                                   "ступеней в ней не заложено."}

    # Хвост каждого имени — мера или разрез. Различаем по НАБОРУ хвостов формы,
    # а не по отдельному имени: одна графа «за неделю» ничего не доказывает,
    # а форма, где ВСЕ хвосты — разрезы, показателей в разрезах и содержит.
    tails: List[str] = []
    for segs in with_sep:
        tail = segs[-1]
        if tail not in tails:
            tails.append(tail)
    slice_tails = [t for t in tails if is_slice_tail(t)]

    if len(slice_tails) == len(tails):
        return {**empty, "separator": sep, "kind": KIND_SLICES,
                "fields_with_separator": total, "measures": tails,
                "reason": ("Разделитель есть, но все хвосты имён — разрезы одного "
                           f"показателя ({', '.join(f'«{t}»' for t in tails[:3])}). "
                           "Это не ступени: ступеней в форме не заложено.")}

    # Ступени — сегменты до последнего. Ступень с номером i есть у графы, если
    # сегментов в ней больше i + 1 (последний всегда мера).
    levels: List[Dict] = []
    for i in range(max(len(s) for s in with_sep) - 1):
        present = [s for s in with_sep if len(s) > i + 1]
        if len(present) / total < LEVEL_PRESENCE:
            break
        values: List[str] = []
        for segs in present:
            # Свод («ИТОГО · Принято, ед.») содержит в себе остальные и
            # значением ступени быть не может: встав строкой рядом со своими
            # частями, он сделал бы первый экран суммой, посчитанной дважды.
            if segs[i] in values or is_total_column(" · ".join(segs)):
                continue
            values.append(segs[i])
        levels.append({"index": i, "values": values, "count": len(values),
                       "fields": len(present)})

    if not levels:
        return {**empty, "separator": sep, "fields_with_separator": total,
                "measures": tails,
                "reason": "Разделитель есть, но ни одна ступень не встречается "
                          "хотя бы у двух третей граф — форма плоская."}

    return {"kind": KIND_HIERARCHY, "separator": sep, "levels": levels,
            "measures": [t for t in tails if not is_slice_tail(t)],
            "fields_total": len(clean_names), "fields_with_separator": total,
            "reason": (f"Имена граф собраны через «{sep.strip()}» из "
                       f"{len(levels) + 1} частей: {len(levels)} "
                       f"{_plural(len(levels), 'ступень', 'ступени', 'ступеней')} и мера.")}


def _by_volume(items: List[Dict], total: float) -> List[Dict]:
    """Строки по убыванию объёма, с проставленной долей."""
    rows = sorted(items, key=lambda i: -abs(float(i.get("volume") or 0)))
    for it in rows:
        it["share"] = (abs(float(it.get("volume") or 0)) / total) if total else 0.0
    return rows


def group_lone(values: Sequence[Dict], threshold: float = LONE_SHARE) -> Dict:
    """Свести одинокие значения первой ступени в общий узел.

    Решение заказчика (09.09): «система сама сводит одинокие значения в узел
    „Отдельные услуги", показывает в мастере, человек подтверждает».

    Зачем это вообще нужно. Распознавание даёт у РЦО 46 значений первой
    ступени, и вперемешку с «Росреестром» там стоят одинокие услуги вроде
    «(487) Идентификация личности для оформления карты болельщика» — на первом
    экране это не список ведомств, а свалка. Но «эта услуга — мелочь» суждение
    о смысле, поэтому система его предлагает, а не применяет молча.

    🔴 Одиноким значение делают ДВА признака сразу, и второй добавлен по
    замеру, а не из осторожности:

      • у него нет своей подступени (все графы двухсегментные) — признак
        структурный и устойчивый;
      • его объём мал.

    Одного первого признака НЕ хватает: ЕСИА, ЗАГС и ОМС тоже не имеют
    подступени («источник не даёт разбивки по уровню „Услуга"» — решение
    заказчика 08.09), но ЕСИА это 23,9 % объёма формы, второй по величине
    блок. Свести его в «Отдельные услуги» значило бы спрятать главное.

    🔴 Объём берётся по ВСЕЙ истории выпусков, а не по последнему отчёту.
    Замер на РЦО: у «Администрации м.о. Горловка» десять услуг и ноль
    обращений за 31.08 — по одному дню она выглядит пустышкой, хотя это
    настоящее ведомство с настоящей структурой. Тот же урок, что уже стоил
    правки при отборе показателей 02.09: последним выпуском оказался
    незаполненный лист, и сортировка по нему была лотереей.

    Значение со своей подступенью в узел не уходит НИКОГДА, каким бы малым ни
    был объём: структура в форме заложена, и прятать её нельзя.
    """
    items = [dict(v) for v in values]
    total = sum(abs(float(i.get("volume") or 0)) for i in items)

    # 🔴 На ОДНОСТУПЕНЧАТОЙ форме не группируем вовсе. Признак «нет своей
    # подступени» там верен для каждого значения и потому не различает ничего:
    # правило вырождается в чистый отбор по объёму, а распределение у госформ
    # длиннохвостое. Замер: у «Статистики услуг — МВД» из 29 услуг в узел
    # уходили 26 — на экране оставалось четыре строки вместо формы.
    #
    # Группировка задумана для другого случая: первая ступень — ведомства, и
    # среди них затесались одинокие услуги без ведомства. Нет второй ступени —
    # нет и этого случая.
    if not any(i.get("has_children") for i in items):
        return {"rows": _by_volume(items, total), "lone": [], "node": None,
                "reason": "У формы одна ступень — сводить нечего: "
                          "каждое значение здесь и есть предмет."}

    if len(items) <= GROUP_FROM_ROWS:
        short = _by_volume(items, total)
        return {"rows": short, "lone": [], "node": None,
                "reason": f"Значений всего {len(items)} — список читается целиком, "
                          "сводить нечего."}

    rows: List[Dict] = []
    lone: List[Dict] = []
    for it in items:
        vol = abs(float(it.get("volume") or 0))
        share = (vol / total) if total else 0.0
        it["share"] = share
        # Нечем судить (объёма нет вовсе — данные ещё не выпущены) — не
        # группируем: пустой узел «Отдельные услуги» на всю форму хуже
        # длинного, но честного списка.
        if it.get("has_children") or not total or share >= threshold:
            rows.append(it)
        else:
            lone.append(it)

    rows.sort(key=lambda i: -abs(float(i.get("volume") or 0)))
    node = None
    if lone:
        node = {"value": LONE_NODE, "volume": sum(abs(float(i.get("volume") or 0)) for i in lone),
                "share": sum(i["share"] for i in lone), "has_children": True,
                "grouped": [i["value"] for i in lone], "is_group": True}
        rows.append(node)   # узел ставим в конец: он по определению мелкий

    return {"rows": rows, "lone": lone, "node": node,
            "reason": (f"{len(lone)} "
                       f"{_plural(len(lone), 'значение', 'значения', 'значений')} "
                       f"без своей подступени дают вместе "
                       f"{(node['share'] * 100) if node else 0:.1f} % объёма — "
                       f"сведены в «{LONE_NODE}»." if lone else
                       "Одиноких значений нет — сводить нечего.")}
