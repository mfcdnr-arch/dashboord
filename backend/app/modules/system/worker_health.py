"""Живость фонового воркера — по СОБСТВЕННОМУ health-ключу arq.

Зачем отдельный модуль. Воркер (`arq`) выполняет весь конвейер, которого не
видно на экране: распознавание загруженных файлов, авто-выпуск данных,
уведомления, ежедневную проверку свежести, ретенцию, автоархив и сторожевую
самодиагностику `system_watchdog`. Его остановка не даёт НИ ОДНОГО видимого
признака: дашборды продолжают показывать прежние цифры, загрузка файла
проходит, и только через день-другой человек замечает, что данные не
обновляются. Сторож при этом молчит по устройству — он живёт ВНУТРИ воркера и
умирает вместе с ним, поэтому обнаружить смерть может только сторона API.

Своего heartbeat НЕ заводим: arq пишет health-ключ сам (`record_health`),
раз в `health_check_interval` секунд, с TTL = интервал + 1 с. Ключ исчезает
сам, если воркер перестал его обновлять, — то есть «протухание» обеспечено
Redis, а не нашим кодом. Второй механизм поверх готового означал бы два
источника правды о живости, которые однажды разойдутся.

Содержимое ключа arq (строка):
    Sep-15 12:34:56 j_complete=5 j_failed=0 j_retried=0 j_ongoing=0 queued=0
Отсюда берём очередь и счётчик отказов: живой воркер с растущей очередью —
тоже повод вмешаться, хотя формально он «ok».
"""
from __future__ import annotations

import re

from arq.constants import default_queue_name, health_check_key_suffix

from ... import cache

# Ключ собирается из констант самого arq, а не вписан строкой: при смене
# суффикса в библиотеке мы поедем за ней. Имя очереди у проекта по умолчанию —
# `WorkerSettings` его не переопределяет; что это по-прежнему так, держит тест
# `test_worker_health.py` (иначе API читал бы ключ, которого воркер не пишет).
HEALTH_KEY = default_queue_name + health_check_key_suffix

_NUM = re.compile(r"(\w+)=(\d+)")


def parse_info(raw: str) -> dict:
    """Числа из строки arq. Неизвестные поля игнорируем — формат не наш."""
    return {k: int(v) for k, v in _NUM.findall(raw or "")}


async def read() -> dict:
    """Состояние воркера для экранов и проверок.

    state: `ok` — ключ свежий; `down` — Redis доступен, а ключа нет (воркер
    молчит дольше интервала); `unknown` — сам Redis недоступен, и судить о
    воркере не по чему. Третье состояние не формальность: показать «воркер
    упал», когда на самом деле лежит Redis, значит послать человека чинить
    не то.
    """
    redis_ok, raw = await cache.get_checked(HEALTH_KEY)
    if not redis_ok:
        return {"state": "unknown", "ok": False, "detail": "Redis недоступен — живость воркера не проверить"}
    if not raw:
        return {"state": "down", "ok": False,
                "detail": "Воркер не отмечался дольше отведённого времени: загрузка файлов, "
                          "выпуск данных и уведомления остановлены"}
    nums = parse_info(raw)
    return {
        "state": "ok", "ok": True, "detail": raw,
        "queued": nums.get("queued"), "failed": nums.get("j_failed"),
        "ongoing": nums.get("j_ongoing"), "complete": nums.get("j_complete"),
    }
