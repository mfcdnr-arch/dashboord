"""Памятка на время расчёта ОДНОЙ страницы дашборда.

Зачем. После устранения главного N+1 на «Обзоре» РЦО оставалось 261 обращение к
базе, и две трети из них — справочные повторы: «какой выпуск датасета активен»
(77 раз) и «как называется этот столбец» (49 раз). Задаются они на каждое поле
каждого виджета, а ответ в пределах одного расчёта не меняется.

Почему контекстная переменная, а не параметр. Прокинуть словарь пришлось бы
через десяток функций-источников и через все будущие; про параметр однажды
забудут, и повтор вернётся незаметно. Контекст ставится в одном месте — там,
где начинается расчёт страницы.

🔴 Главный риск — не производительность, а протечка. Памятка живёт РОВНО внутри
`page_scope()` и обязана исчезать после него: кэш, переживший запрос, отдаёт
данные «из прошлого раза». А ключ обязан включать организацию и дату, иначе
виджет покажет чужие данные — и выглядеть это будет совершенно правдоподобно.
Оба свойства держат тесты в `test_page_calc_memo.py`.
"""
from __future__ import annotations

import contextvars
from contextlib import contextmanager
from typing import Any, Awaitable, Callable, Optional

_cache: contextvars.ContextVar[Optional[dict]] = contextvars.ContextVar("page_calc_cache", default=None)


@contextmanager
def page_scope():
    """Границы одного расчёта страницы. Вне его памятки нет вовсе."""
    token = _cache.set({})
    try:
        yield
    finally:
        _cache.reset(token)


async def memo(key: tuple, load: Callable[[], Awaitable[Any]]) -> Any:
    """Ответ на справочный вопрос — один раз за расчёт страницы.

    Вне `page_scope()` просто выполняет запрос: одиночный виджет, выгрузка и
    предпросмотр не должны получать значения, отвеченные когда-то раньше.
    """
    store = _cache.get()
    if store is None:
        return await load()
    if key in store:
        return store[key]
    # Ошибку НЕ запоминаем: сбой одного виджета не должен наследоваться всеми
    # остальными на странице — они попробуют сами.
    value = await load()
    store[key] = value
    return value
