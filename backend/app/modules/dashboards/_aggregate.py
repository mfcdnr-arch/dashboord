"""Как сворачивать строки датасета в одно число.

Виджет-карточка показывает ОДНО значение по столбцу, в котором строк может
быть много (субъект, район, отделение). Для количеств это сумма, а для долей
и процентов сумма — бессмыслица: «12,4 % + 9,8 % + 31,0 %» = 53,2 % не значит
ничего, но выглядит как настоящий показатель и потому опаснее пустого места.

Правило то же, что в предпросмотре разметки (`DashboardDraft.aggregate`), —
одно на систему: иначе один и тот же столбец давал бы в конструкторе одно
число, а на дашборде другое.

Среднее по строкам — тоже упрощение: правильная доля считается из числителя и
знаменателя, а их у столбца-процента уже нет. Поэтому среднее не выдаётся за
точный итог: расчёт возвращает признак `aggregate`, и карточка подписывает
«среднее по N строкам».
"""
from __future__ import annotations

import re
from typing import Iterable, Optional, Tuple

# «%», «доля», «удельный вес», «средн…» — так подписаны относительные величины
# в госформах. Проверяем ИМЯ показателя (в нём единица и живёт) и явную единицу
# виджета, если человек задал её руками.
_SHARE_RE = re.compile(r"%|доля|удельн|средн", re.IGNORECASE)

# 🔴 Явно названная единица КОЛИЧЕСТВА отменяет догадку по словам.
#
# Правило выше ищет приметы доли ВНУТРИ всего имени, и на длинных названиях
# госуслуг это даёт ложные срабатывания: «…организации общедоступного и
# бесплатного дошкольного, начального общего, основного общего и СРЕДНЕГО
# общего образования…» ловится по «средн», а «Компенсация 50% ОСАГО
# инвалидам» — по «%». Обе графы — количества, и обе кончаются на «, ед.».
#
# Замер по ВСЕМ 766 графам системы: правило срабатывает на 6 из них, у 5 в
# имени стоит «, ед.» (то есть форма прямо назвала единицу количества), и лишь
# одна — настоящая доля, «% достижения показателя». То есть оговорка убирает
# ровно ложные срабатывания и не трогает ни одной верной.
#
# Цена ошибки была не косметическая: карточка по такой графе возвращала
# aggregate='avg' и делила сумму на 62 отделения. Сегодня это незаметно —
# значения нулевые, — но с первым же обращением показала бы 1 вместо 62.
_COUNT_UNIT_RE = re.compile(r",\s*(ед|шт|чел)\.?", re.IGNORECASE)


def is_share(name: Optional[str], unit: Optional[str] = None) -> bool:
    """Относительная величина (её нельзя складывать) или обычное количество."""
    text = f"{name or ''} {unit or ''}"
    if _COUNT_UNIT_RE.search(text):
        return False
    return bool(_SHARE_RE.search(text))


def aggregate_series(values: Iterable[float], name: Optional[str],
                     unit: Optional[str] = None) -> Tuple[float, str]:
    """Значение по столбцу и способ, которым оно получено ('sum' | 'avg')."""
    vals = [float(v) for v in values]
    if not vals:
        return 0.0, "sum"
    if is_share(name, unit):
        return sum(vals) / len(vals), "avg"
    return sum(vals), "sum"


# ─────────────────────────────────────────────────────────────────────────────
# Что с чем складывается: устройство ИМЕНИ графы
#
# Правило `is_share` выше отвечает на вопрос «складывать или усреднять ОДНУ
# графу по строкам». Ниже — второй вопрос того же рода: «можно ли складывать
# РАЗНЫЕ графы между собой». Ответов у него два, и оба про имя:
#
#   • графа-свод («ИТОГО · Принято, ед.») уже содержит в себе остальные —
#     сложив её с ними, обращение считаем дважды;
#   • графы с разным хвостом («Принято» и «Выдано») измеряют разные стадии
#     ОДНОГО обращения — их сумма тоже двойной счёт.
#
# Оба правила уже жили в проверках качества выпуска (`ingestion.quality`) и в
# виджете «Показатели списком», но каждое в своём экземпляре. Здесь их общий
# дом: два понятия об «итоге» однажды разошлись бы, и спорить пришлось бы уже
# о них, а не о данных.
# ─────────────────────────────────────────────────────────────────────────────

# Свод и в СТРОКАХ формы («Итого по региону»), и в ГРАФАХ («ИТОГО · Принято»).
TOTAL_LABEL_RE = re.compile(r"итог|всего", re.IGNORECASE)

# Разделитель сегментов имени госформы — тот же « · », что и в разборе имён
# (`metrics.data_suggestions._split_name`), и та же очистка сегмента: она
# убирает сноски-звёздочки («нарастающим итогом**»), без чего два одинаковых по
# смыслу хвоста считались бы разными.
_SEP_RE = re.compile(r"\s*·\s*")


def head_tail(name: Optional[str]) -> Tuple[str, str]:
    """Имя графы → (всё до последнего разделителя, последний сегмент).

    У формы РЦО имена устроены как «Ведомство · Услуга · Показатель», поэтому
    хвост — это ЧТО измеряет графа («Принято, ед.»), а голова — про кого.
    Имя без разделителя даёт пустую голову: такая форма своего устройства не
    называет, и правила, опирающиеся на устройство, обязаны молчать.
    """
    from ..metrics.data_suggestions import _clean  # локально: модуль тянет разбор формул

    parts = [c for c in (_clean(p) for p in _SEP_RE.split(name or "")) if c]
    if not parts:
        return "", ""
    return " · ".join(parts[:-1]), parts[-1]


def is_total_column(name: Optional[str]) -> bool:
    """Графа-свод: «ИТОГО · Принято, ед.» рядом с «Ведомство · Услуга · Принято, ед.».

    🔴 Ищем ПО ИМЕНИ, а не арифметикой — хотя в проекте есть и второй приём
    («Показатели списком» опознаёт итог равенством сумме остальных). Здесь
    арифметика не годится ПРИНЦИПИАЛЬНО: виджет показывает не всю форму, а те
    графы, которые выбрал человек, и «ИТОГО · Принято» = 5 426 рядом с двумя
    выбранными услугами (2 885 и 441) сумме остальных не равен — по равенству
    свод не нашёлся бы никогда, а в сумму по строке он всё равно попадает.

    Слово ищем в ГОЛОВЕ имени: услуга со словом «итог» в названии иначе
    объявила бы итогом сама себя.
    """
    head, tail = head_tail(name)
    if not head or not tail:
        return False
    return bool(TOTAL_LABEL_RE.search(head))


def subject_with_measure(name: Optional[str]) -> str:
    """Как назвать показатель в заголовке виджета: предмет и, если нужно, МЕРА.

    🔴 Заведено по замечанию заказчика «непонятно, что это за показатели». У
    формы РЦО первый сегмент имени — это ВЕДОМСТВО («ИТОГО», «Росреестр», «ЕСИА
    (260)»), и виджет, названный по нему, отвечал «ИТОГО: по отделениям» — по
    отделениям ЧТО? У формы МАХ первый сегмент, наоборот, и есть полное имя
    показателя («Количество обращений за результатом оказания услуг в МФЦ»), и
    дописывать к нему хвост значило бы удлинять и без того длинное имя.

    Различаем эти два случая ПО ДАННЫМ, а не по длине: меру дописываем тогда,
    когда хвост имени назвал ЕДИНИЦУ («Принято, ед.», «Отказ, ед.»). Хвост без
    единицы — это разрез («нарастающим итогом»), а не мера, и предмет в таком
    имени уже назван первым сегментом.
    """
    head, tail = head_tail(name)
    subject = head.split(" · ")[0] if head else (tail or "")
    if not head or not tail:
        return subject or (name or "")
    if _COUNT_UNIT_RE.search(tail) or "%" in tail:
        return f"{subject} · {tail}"
    return subject


def measure_of(name: Optional[str]) -> str:
    """Что измеряет графа — хвост имени; пусто, если форма не назвала устройство."""
    head, tail = head_tail(name)
    return tail if head else ""
