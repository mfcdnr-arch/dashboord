"""Как сворачивать строки датасета в одно число.

Виджет-карточка показывает ОДНО значение по столбцу, в котором строк может
быть много (субъект, район, отделение). Для количеств это сумма, а для долей
и процентов сумма — бессмыслица: «12,4 % + 9,8 % + 31,0 %» = 53,2 % не значит
ничего, но выглядит как настоящий показатель и потому опаснее пустого места.

Правило то же, что в предпросмотре разметки (`DashboardDraft.aggregate`), —
одно на систему: иначе один и тот же столбец давал бы в конструкторе одно
число, а на дашборде другое.

Среднее по строкам — тоже упрощение: правильная доля считается из числителя и
знаменателя, а их у столбца-процента уже нет. Поэтому среднее не выдаётся за
точный итог: расчёт возвращает признак `aggregate`, и карточка подписывает
«среднее по N строкам».
"""
from __future__ import annotations

import re
from typing import Iterable, Optional, Tuple

# «%», «доля», «удельный вес», «средн…» — так подписаны относительные величины
# в госформах. Проверяем ИМЯ показателя (в нём единица и живёт) и явную единицу
# виджета, если человек задал её руками.
_SHARE_RE = re.compile(r"%|доля|удельн|средн", re.IGNORECASE)


def is_share(name: Optional[str], unit: Optional[str] = None) -> bool:
    """Относительная величина (её нельзя складывать) или обычное количество."""
    return bool(_SHARE_RE.search(f"{name or ''} {unit or ''}"))


def aggregate_series(values: Iterable[float], name: Optional[str],
                     unit: Optional[str] = None) -> Tuple[float, str]:
    """Значение по столбцу и способ, которым оно получено ('sum' | 'avg')."""
    vals = [float(v) for v in values]
    if not vals:
        return 0.0, "sum"
    if is_share(name, unit):
        return sum(vals) / len(vals), "avg"
    return sum(vals), "sum"
