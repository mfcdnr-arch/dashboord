"""Книга, где ЛИСТ = отчётная дата.

Файлы РЦО устроены не так, как всё, что грузили раньше: один файл несёт
историю — 12 листов в «Окнах и часах» и 189 в «Ежедневном отчёте», по листу на
рабочий день. Раскладывать их руками по одному документу на дату — 189
загрузок.

Проверяется то, на чём этот механизм ломается молча: разбор даты из имени листа
(года там нет) и отказ гадать, когда имя датой не является.
"""
from datetime import date

from app.modules.ingestion.mapping import sheet_date


def test_sheet_name_becomes_a_reporting_date():
    """«17.08» + год из настройки загрузки."""
    assert sheet_date("17.08", 2026) == date(2026, 8, 17)
    assert sheet_date("01.09", 2026) == date(2026, 9, 1)
    assert sheet_date(" 12.01 ", 2026) == date(2026, 1, 12)
    assert sheet_date("17/08", 2026) == date(2026, 8, 17)


def test_year_in_the_sheet_name_wins_over_the_setting():
    """Если год написан на листе — он и берётся, а не подставленный.

    Иначе книга за прошлый год, загруженная с годом по умолчанию, молча создала
    бы выпуски не той даты, и вся динамика уехала бы на год.
    """
    assert sheet_date("17.08.2025", 2026) == date(2025, 8, 17)
    assert sheet_date("17.08.25", 2026) == date(2025, 8, 17)


def test_a_sheet_that_is_not_a_date_is_refused():
    """🔴 Молчаливого угадывания быть не должно.

    В книгах заказчика рядом с датами живут служебные листы («проверка»,
    «Перечень услуг»). Выпуск по ним создавать нельзя, а отказ обязан быть
    видимым — он уезжает в отчёт загрузки построчно.
    """
    for bad in ("Свод", "проверка", "Перечень услуг (новый)", "", None, "лист1"):
        assert sheet_date(bad, 2026) is None, bad


def test_impossible_date_is_not_invented():
    """«40.09» — опечатка в имени листа, а не дата. Тот же принцип, что у
    разбора срока термометра: выдуманная дата хуже отсутствующей."""
    assert sheet_date("40.09", 2026) is None
    assert sheet_date("17.13", 2026) is None
    assert sheet_date("30.02", 2026) is None
