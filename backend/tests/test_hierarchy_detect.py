STATS = ["Услуга 1: Принято", "Услуга 1: Выдано", "Услуга 2: Принято",
         "Услуга 2: Приоритетная услуга", "Услуга 29: Выдано"]
KPE = ["Показатель", "План", "Факт", "% достижения показателя", "Единица измерения"]


def test_rco_form_has_two_levels_and_a_measure():
    """Форма РЦО: «ведомство · услуга · мера» — две ступени, мера отдельно."""
    res = detect_levels(RCO)
    assert res["kind"] == KIND_HIERARCHY
    assert res["separator"] == " · "
    assert len(res["levels"]) == 2
    # Мера — это ЧТО измеряем, ступенью она не становится.
    assert set(res["measures"]) == {"Принято, ед.", "Выдано, ед.", "Отказ, ед."}
    # Свод не значение ступени: встав строкой рядом со своими частями, он
    # сделал бы первый экран суммой, посчитанной дважды.
    assert "ИТОГО" not in res["levels"][0]["values"]
    assert {"Росреестр", "МВД", "ЕСИА (260)"} <= set(res["levels"][0]["values"])
    # Вторая ступень — услуги, а не меры.
    assert "Государственный кадастровый учет" in res["levels"][1]["values"]
    assert "Принято, ед." not in res["levels"][1]["values"]


def test_max_form_is_slices_not_levels():
    """🔴 Главная защита: разрезы показателя не выдаются за ступени.

    Разделитель тот же, что у РЦО, но все хвосты имён — разрезы и роли, а
    значит ступеней в форме не заложено. Ошибись правило здесь — на дашборде
    появилась бы лестница, где «Факт» и «План» стоят вместо услуг.
    """
    res = detect_levels(MAX_FORM)
    assert res["kind"] == KIND_SLICES
    assert res["levels"] == []
    assert "разрез" in res["reason"].lower()


def test_flat_form_says_so_plainly():
    """Разделителя нет вовсе — честное «плоская форма», а не выдуманные уровни."""
    res = detect_levels(KPE)
    assert res["kind"] == KIND_FLAT
    assert res["levels"] == []
    assert res["separator"] is None


def test_statistics_form_uses_its_own_separator():
    """«Статистика услуг» разделена двоеточием, и ступень там одна."""
    res = detect_levels(STATS)
    assert res["kind"] == KIND_HIERARCHY
    assert res["separator"] == ":"
    assert len(res["levels"]) == 1
    assert "Услуга 1" in res["levels"][0]["values"]


def test_separator_inside_a_service_name_does_not_make_a_third_level():
    """Порог ⅔ отсекает « · » внутри длинного названия услуги.

    У РЦО пять граф из 331 имеют четыре сегмента — не потому, что есть
    четвёртая ступень, а потому что разделитель попал внутрь названия услуги
    ФНС. Без порога система предложила бы ступень, которой в форме нет.
    """
    names = RCO + ["ФНС · Прием заявления о предоставлении справки · о сальдо счета · Принято, ед."]
    res = detect_levels(names)
    assert len(res["levels"]) == 2, "четвёртый сегмент у одной графы — не ступень"


def _filler(n, volume=500.0, has_children=True):
    """Ведомства-наполнители: без них список короче порога и не группируется вовсе."""
    return [{"value": f"Ведомство {i}", "volume": volume, "has_children": has_children}
            for i in range(n)]


def test_short_list_is_not_grouped_at_all():
    """Короткий список остаётся целым, даже когда одинокие в нём есть.

    Порог не косметический: первый экран лестницы рисует «Ранжированный
    список», а он показывает 12 строк. Если список в него и так помещается,
    узел «Отдельные услуги» ничего не упрощает, зато прячет часть формы за
    лишним щелчком.
    """
    g = group_lone([
        {"value": "Росреестр", "volume": 199811, "has_children": True},
        {"value": "ЕСИА (260)", "volume": 114048, "has_children": False},
        {"value": "Апостиль", "volume": 39, "has_children": False},
    ])
    assert g["node"] is None
    assert len(g["rows"]) == 3
    assert "целиком" in g["reason"]


def test_lone_values_are_grouped_but_large_ones_stay():
    """Одинокие сводятся в узел; крупное без подступени остаётся строкой.

    Числа — доли объёма по всей истории РЦО (53 отчёта): ЕСИА 23,9 %, ЗАГС
    8,5 %, ОМС 4,85 %, а следующее за ними значение уже 0,4 %. Свести ЕСИА в
    «Отдельные услуги» значило бы спрятать второй по величине блок формы.
    """
    g = group_lone([
        {"value": "Росреестр", "volume": 199811, "has_children": True},
        {"value": "ЕСИА (260)", "volume": 114048, "has_children": False},
        {"value": "ОМС (297, 299)", "volume": 23136, "has_children": False},
        {"value": "УКЭП (483)", "volume": 1282, "has_children": False},
        {"value": "Апостиль (347, 348)", "volume": 39, "has_children": False},
    ] + _filler(10))
    names = [r["value"] for r in g["rows"]]
    assert "ЕСИА (260)" in names and "ОМС (297, 299)" in names
    assert "УКЭП (483)" not in names and "Апостиль (347, 348)" not in names
    assert g["node"]["value"] == LONE_NODE
    assert set(g["node"]["grouped"]) == {"УКЭП (483)", "Апостиль (347, 348)"}
    assert names[0] == "Росреестр", "строки идут по величине"
    assert names[-1] == LONE_NODE, "узел стоит в конце — он по определению мелкий"


def test_structure_is_never_hidden_even_at_zero_volume():
    """🔴 Значение со своей подступенью не уходит в узел даже с нулём.

    На РЦО у «Администрации м.о. Горловка» десять услуг и ноль обращений —
    по объёму она выглядит пустышкой, но структура в форме заложена, и прятать
    её нельзя: завтра обращения появятся, а строки на экране не будет.
    """
    g = group_lone([
        {"value": "Росреестр", "volume": 199811, "has_children": True},
        {"value": "Администрация м.о. Горловка", "volume": 0, "has_children": True},
        {"value": "Апостиль", "volume": 39, "has_children": False},
    ] + _filler(12))
    assert "Администрация м.о. Горловка" in [r["value"] for r in g["rows"]]
    assert g["node"]["grouped"] == ["Апостиль"]


def test_without_volume_nothing_is_grouped():
    """Данных ещё нет — судить не по чему, список остаётся полным."""
    g = group_lone(_filler(20, volume=0) +
                   [{"value": "Апостиль", "volume": 0, "has_children": False}])
    assert g["node"] is None
    assert len(g["rows"]) == 21


def test_single_level_form_is_never_grouped():
    """🔴 У одноступенчатой формы группировки нет вовсе — найдено живой проверкой.

    Признак «нет своей подступени» там верен для КАЖДОГО значения и потому не
    различает ничего: правило вырождается в отбор по объёму, а распределение у
    госформ длиннохвостое. Замер на «Статистике услуг — МВД»: из 29 услуг в
    узел уходили 26, на экране оставалось четыре строки вместо формы.
    """
    services = [{"value": f"Услуга {i}", "volume": max(1, 3000 // (i + 1)),
                 "has_children": False} for i in range(29)]
    g = group_lone(services)
    assert g["node"] is None
    assert len(g["rows"]) == 29, "ни одна услуга не спрятана"
    assert "одна ступень" in g["reason"]
