"""Внутренняя сверка формы (п. 13): арифметика ВНУТРИ одного файла.

До этого `quality.py` умел только сравнивать файл С ПРОШЛОЙ НЕДЕЛЕЙ. Следствие
было хуже, чем «чего-то не проверяем»: на ПЕРВОМ файле формы не срабатывало
НИ ОДНО правило — даже те, которым прошлый отчёт не нужен. Именно там ошибку
заметить сложнее всего: сравнить не с чем ни системе, ни человеку.

Три правила, названные заказчиком:

1. **Сумма по строкам против строки «Итого»** — окупается, когда пойдут районы.
2. **«За неделю» не больше накопительного итога** — правило существовало, но
   жило внутри сверки с прошлым и вместе с ней молчало на первом файле.
3. **Факт превышает план** — и здесь главное не «поймать», а НЕ поднимать
   ложную тревогу: у заказчика перевыполнение штатное (656 %), потому что план
   задан на срок. Правило обязано молчать на его данных и срабатывать там, где
   план и факт заданы в одном разрезе.
"""
from app.modules.ingestion import quality

NAMES = {
    "obr_total": "Количество обращений · Факт · нарастающим итогом",
    "obr_week": "Количество обращений · Факт · за отчётную неделю",
    "uved_total": "Количество уведомлений · Факт · нарастающим итогом",
    "dolya": "Доля доставленных · Факт · нарастающим итогом, %",
}

# Имена граф ЗАКАЗЧИКА, слово в слово из его справочника: план задан на срок,
# факт идёт нарастающим итогом. На них правило «факт больше плана» обязано
# молчать — иначе оно срабатывало бы каждую неделю по всем показателям.
REAL = {
    "plan": ("Количество успешно доставленных уведомлений о готовности результата оказания "
             "услуг в МФЦ (по данным ЛК Notify) · План (до 1 сентября 2026 г.)*"),
    "fact": ("Количество успешно доставленных уведомлений о готовности результата оказания "
             "услуг в МФЦ (по данным ЛК Notify) · Факт · нарастающим итогом**"),
}

# Недельная форма районов: план и факт в ОДНОМ разрезе — здесь сравнивать можно.
WEEKLY = {
    "plan_w": "Заявок принято · План · за отчетную неделю",
    "fact_w": "Заявок принято · Факт · за отчетную неделю",
}


def _codes(warnings):
    return {w["code"] for w in warnings}


def test_sum_of_rows_must_match_total_row():
    """Сумма по районам против строки «Итого» — и допуск на округление."""
    cur = {
        ("Донецк", "obr_total"): 100.0,
        ("Макеевка", "obr_total"): 200.0,
        ("Горловка", "obr_total"): 300.0,
        ("Итого", "obr_total"): 900.0,          # должно быть 600 — район потерян
    }
    w = quality.check_internal(cur, NAMES)
    bad = [x for x in w if x["code"] == "total_row_mismatch"]
    assert bad, w
    assert "600" in bad[0]["message"] and "900" in bad[0]["message"]

    # Сходится — молчим.
    ok = {**cur, ("Итого", "obr_total"): 600.0}
    assert "total_row_mismatch" not in _codes(quality.check_internal(ok, NAMES))

    # Расхождение в единицу — округление, а не ошибка заполнения.
    rounded = {**cur, ("Итого", "obr_total"): 601.0}
    assert "total_row_mismatch" not in _codes(quality.check_internal(rounded, NAMES))


def test_total_row_rule_knows_when_to_keep_quiet():
    """Правило молчит там, где сумма бессмысленна или структура неясна."""
    # Проценты складывать нельзя — «итог» по доле это не сумма долей.
    shares = {("Донецк", "dolya"): 40.0, ("Макеевка", "dolya"): 50.0,
              ("Итого", "dolya"): 45.0}
    assert "total_row_mismatch" not in _codes(quality.check_internal(shares, NAMES))

    # Две «итоговых» подписи — структуру формы мы не понимаем; гадать нельзя.
    two = {("Итого по МФЦ", "obr_total"): 10.0, ("Всего", "obr_total"): 999.0,
           ("Донецк", "obr_total"): 3.0, ("Макеевка", "obr_total"): 4.0}
    assert "total_row_mismatch" not in _codes(quality.check_internal(two, NAMES))

    # Одна строка данных плюс итог: «сумма» совпала бы с самой строкой, и
    # правило превратилось бы в проверку «строка равна итогу». Это форма
    # заказчика — на ней правило обязано молчать.
    single = {("Донецкая Народная Республика", "obr_total"): 1000864.0,
              ("Итого", "obr_total"): 1000864.0}
    assert "total_row_mismatch" not in _codes(quality.check_internal(single, NAMES))

    # Итоговой строки нет вовсе — сверять не с чем.
    plain = {("Донецк", "obr_total"): 1.0, ("Макеевка", "obr_total"): 2.0}
    assert "total_row_mismatch" not in _codes(quality.check_internal(plain, NAMES))


def test_fact_over_plan_is_silent_on_customer_data():
    """🔴 Главная проверка правила «факт больше плана» — что оно МОЛЧИТ.

    План заказчика задан «до 1 сентября» (разрез «other»), факт идёт
    нарастающим итогом. Разрезы разные — значит несопоставимы, и превышение в
    656 % это не ошибка данных, а нормальное перевыполнение к сроку. Сработай
    правило здесь — оно кричало бы каждую неделю по всем показателям и
    приучило бы пропускать замечания вообще.
    """
    cur = {("ДНР", "plan"): 41971.0, ("ДНР", "fact"): 275694.0}   # 656 %
    assert "fact_over_plan" not in _codes(quality.check_internal(cur, REAL))


def test_fact_over_plan_fires_when_slices_match():
    """А там, где план и факт заданы в ОДНОМ разрезе, превышение видно."""
    cur = {("Донецк", "plan_w"): 100.0, ("Донецк", "fact_w"): 450.0}
    bad = [x for x in quality.check_internal(cur, WEEKLY) if x["code"] == "fact_over_plan"]
    assert bad, "недельный план против недельного факта сопоставим"
    assert "450" in bad[0]["message"] and "100" in bad[0]["message"]

    # Факт в пределах плана — молчим.
    assert "fact_over_plan" not in _codes(
        quality.check_internal({("Донецк", "plan_w"): 100.0, ("Донецк", "fact_w"): 90.0}, WEEKLY))

    # Плана нет (0) — это незаполненная графа, а не перевыполнение: «∞ %»
    # ничего не сообщает, и здесь мы молчим.
    assert "fact_over_plan" not in _codes(
        quality.check_internal({("Донецк", "plan_w"): 0.0, ("Донецк", "fact_w"): 90.0}, WEEKLY))


def test_check_release_runs_both_kinds_and_does_not_double_report():
    """`check_release` — единственная точка входа: внутренние + сверка с прошлым.

    Три места показывают эти замечания (предпросмотр выпуска, результат выпуска
    и блок «На что посмотреть»). Если бы каждое собирало правила само, они
    однажды разошлись бы; тест держит их на одной функции и заодно требует,
    чтобы одно замечание не приходило дважды.
    """
    cur = {("ДНР", "obr_total"): 1000.0, ("ДНР", "obr_week"): 5000.0}
    prev = {("ДНР", "obr_total"): 1000.0, ("ДНР", "obr_week"): 5000.0}
    w = quality.check_release(cur, NAMES, prev, "12.08.2026")
    codes = [x["code"] for x in w]
    assert "weekly_over_total" in codes, "внутренняя арифметика"
    assert "same_as_previous" in codes, "сверка с прошлым"
    assert len(codes) == len(set(codes)), f"замечание не должно приходить дважды: {codes}"
