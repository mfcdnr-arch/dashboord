#!/usr/bin/env bash
# Аварийное восстановление доступа суперадминистратора.
#
# Когда нужно. Права устроены так, что суперадмина может трогать только
# суперадмин, а выдавать роль `superadmin` — тоже только он. Поэтому потерянный
# пароль ЕДИНСТВЕННОГО суперадминистратора не восстанавливается из интерфейса
# никак: администратор не может ни сбросить его пароль, ни завести второго.
# Правка SUPERADMIN_PASSWORD в .env.prod тоже не помогает — первичная
# инициализация не трогает пароль уже существующей учётки.
#
# Почему это скрипт на сервере, а не кнопка. Граница безопасности здесь —
# доступ к самой машине: у того, кто имеет shell на сервере, и так есть прямой
# доступ к базе. Кнопка в интерфейсе была бы слабее, а не удобнее.
#
#   ./reset-superadmin.sh                      # сбросить пароль (если он один)
#   ./reset-superadmin.sh --login superadmin   # если суперадминов несколько
#   ./reset-superadmin.sh --grant-to ivanov    # если суперадминов не осталось
#
# Пароль по умолчанию ГЕНЕРИРУЕТСЯ и печатается один раз: переданный аргументом
# остался бы в истории команд и в списке процессов.
set -euo pipefail
cd "$(dirname "$0")"

API_CONTAINER="${API_CONTAINER:-dashbord_prod_api}"

log() { printf '\033[1;34m[reset-superadmin]\033[0m %s\n' "$1"; }
die() { printf '\033[1;31mОШИБКА:\033[0m %s\n' "$1" >&2; exit 1; }

case "${1:-}" in
  -h|--help) sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
esac

docker inspect "$API_CONTAINER" >/dev/null 2>&1 \
  || die "контейнер $API_CONTAINER не запущен — поднимите стек (./deploy.sh) и повторите"

log "Восстановление доступа суперадминистратора…"
# Логика живёт в приложении (app/tools/reset_superadmin.py) и покрыта тестами;
# здесь — только запуск в контейнере, где есть и зависимости, и доступ к БД.
OUT="$(docker exec -i "$API_CONTAINER" python -m app.tools.reset_superadmin "$@")" || {
  echo "$OUT" >&2
  die "восстановить не удалось — прочитайте сообщение выше"
}

LOGIN="$(printf '%s' "$OUT" | python3 -c 'import sys,json;print(json.load(sys.stdin)["login"])')"
PASS="$(printf '%s' "$OUT" | python3 -c 'import sys,json;print(json.load(sys.stdin)["password"])')"
GRANTED="$(printf '%s' "$OUT" | python3 -c 'import sys,json;print(json.load(sys.stdin)["granted"])')"
UNBLOCKED="$(printf '%s' "$OUT" | python3 -c 'import sys,json;print(json.load(sys.stdin)["unblocked"])')"

echo
echo "  ┌─ ДОСТУП ВОССТАНОВЛЕН ────────────────────────────────────────────────────────"
printf "  │  логин           : %s\n" "$LOGIN"
printf "  │  временный пароль: %s\n" "$PASS"
[ "$GRANTED" = "True" ]   && echo "  │  выдана роль суперадминистратора"
[ "$UNBLOCKED" = "True" ] && echo "  │  учётка была заблокирована — разблокирована"
echo "  │"
echo "  │  Пароль ВРЕМЕННЫЙ: система потребует сменить его при первом же входе."
echo "  │  Все прежние сессии этой учётки завершены."
echo "  │  Операция записана в журнал действий (раздел «Отчёты»)."
echo "  └──────────────────────────────────────────────────────────────────────────────"
echo
log "Чтобы это не повторилось, заведите ВТОРОГО суперадминистратора в разделе «Пользователи»."
