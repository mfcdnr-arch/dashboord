import { GAP, ROW_H } from './flowLayout'

/**
 * Плотность страницы дашборда: «просторно» (как было) и «компактно».
 *
 * Зачем: на дашборде заказчика 29 виджетов, и на ноутбуке первый экран
 * вмещает полтора ряда карточек — остальное человек листает. Компактный режим
 * отдаёт под цифры то место, которое занимают поля и промежутки, и на том же
 * экране помещается заметно больше.
 *
 * **Это настройка ЧИТАТЕЛЯ, а не автора страницы** — поэтому она хранится у
 * человека (localStorage), а не в БД рядом с `layout_mode`. Причины две:
 * (1) один и тот же дашборд смотрят и с ноутбука, и с монитора 1920 — верного
 * ответа «для всех» здесь нет; (2) зритель не вправе править страницу, но
 * уплотнить её для себя должен мочь, иначе настройка досталась бы только тем,
 * кому она нужна меньше всего.
 *
 * Компактно меняет ТОЛЬКО поля, промежутки и высоту ряда. Ни состав, ни
 * порядок, ни ширины не трогаются: уплотнение не должно перекладывать
 * страницу — человек ищет глазами то же, что видел секунду назад.
 */
export type Density = 'comfortable' | 'compact'

export interface DensityMetrics {
  /** Высота ряда сетки, px. */
  rowH: number
  /** Промежуток между карточками, px. */
  gap: number
  /** Внутреннее поле карточки, px. */
  pad: number
  /** Размер шрифта заголовка карточки, px. */
  title: number
}

/**
 * «Просторно» повторяет прежние числа страницы (`flowLayout`), чтобы
 * переключатель не изменил вид тем, кто его не трогал.
 *
 * Компактные числа подобраны ЗАМЕРОМ на дашборде заказчика (29 виджетов,
 * окна 1150 и 1400), а не на глаз. Проверялись три варианта:
 *
 * | ряд | выигрыш высоты | карточки показателей | «Динамика» |
 * |-----|----------------|----------------------|------------|
 * | 40 (только поля и промежутки) | −7,8 % | без обрезки | +19px в прокрутку |
 * | **36** | **−15,5 %** | **без обрезки** | **+42px** |
 * | 34 | −19 % | без обрезки | +54px |
 *
 * Взят средний: карточки показателей — а их на странице большинство, и именно
 * ради них дашборд открывают — не режутся ни при какой ширине окна, а выигрыш
 * в пол-экрана того стоит. Ниже 34 опускаться нельзя: там начинает резаться
 * уже само число на карточке.
 *
 * **Честно о цене:** у виджета «Динамика» с двумя строками итогов часть
 * содержимого уходит во внутреннюю прокрутку карточки. Уплотнение тут ни при
 * чём по сути: график уже стоит на своём минимуме (`MIN_CHART_H` = 118px), и в
 * шести рядах сетки этот виджет впритык даже в просторном режиме (замер: запас
 * 1px при окне 1150). Режим выбирает читатель и отменяет одним нажатием.
 */
export const DENSITY: Record<Density, DensityMetrics> = {
  comfortable: { rowH: ROW_H, gap: GAP, pad: 14, title: 13 },
  compact: { rowH: 36, gap: 8, pad: 9, title: 12.5 },
}

export const DENSITY_KEY = 'dashbord_density'

export function loadDensity(): Density {
  try {
    return localStorage.getItem(DENSITY_KEY) === 'compact' ? 'compact' : 'comfortable'
  } catch {
    // Приватный режим браузера запрещает localStorage — плотность не та вещь,
    // из-за которой дашборд имеет право не открыться.
    return 'comfortable'
  }
}

export function saveDensity(d: Density): void {
  try { localStorage.setItem(DENSITY_KEY, d) } catch { /* см. loadDensity */ }
}
