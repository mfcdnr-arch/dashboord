/**
 * Раскладка страницы в режиме «поток».
 *
 * Отличие от свободной сетки: место и размер виджета НЕ хранятся, а считаются
 * по его типу при каждой отрисовке. Так устроены свёрстанные вручную отчёты —
 * полоса карточек, под ней графики, внизу таблицы во всю ширину. Страница не
 * может «поехать», не оставляет дыр и сама уплотняется на широком мониторе.
 *
 * Пропорции — ТЕ ЖЕ, что у авто-сборки на бэкенде (`_suggest.WIDGET_SIZE`):
 * иначе собранная мастером страница выглядела бы одним образом, а та же
 * страница в «потоке» — другим. Соответствие держит тест
 * `backend/tests/test_flow_layout_consistency.py`, который читает этот файл.
 */

/**
 * Ширина в колонках 12-колоночной сетки и высота в рядах по 40px.
 *
 * Числа НЕ равны `_suggest.WIDGET_SIZE` — и это осознанно. Там размеры, которые
 * авто-сборка записывает виджету в СВОБОДНУЮ сетку: график занимает ряд
 * целиком, потому что дальше человек двигает его сам. В «потоке» раскладка
 * пересчитывается при каждой отрисовке, и здесь работает правило свёрстанного
 * отчёта: полоса карточек → графики ПО ДВА в ряд → таблицы во всю ширину.
 * Из-за этого страница из трёх десятков виджетов перестаёт быть лентой.
 * Согласованность классов («что широкое») держит тест
 * `backend/tests/test_flow_layout_consistency.py`.
 */
export const FLOW_SIZE: Record<string, { w: number; h: number }> = {
  // Показатели: полоса вверху страницы.
  kpi: { w: 4, h: 5 },
  // Группа разрезов одного показателя: высота — по содержимому (AUTO_HEIGHT).
  kpi_group: { w: 4, h: 8 },
  gauge: { w: 4, h: 7 },
  dynamics: { w: 4, h: 6 },
  image: { w: 4, h: 5 },
  plan_fact: { w: 6, h: 6 },
  // Графики: по два в ряд.
  bar: { w: 6, h: 7 },
  line: { w: 6, h: 7 },
  pie: { w: 6, h: 6 },
  waterfall: { w: 6, h: 7 },
  yoy: { w: 6, h: 7 },
  compare: { w: 6, h: 8 },
  cross_dataset_compare: { w: 6, h: 8 },
  objects_compare: { w: 6, h: 7 },
  heatmap: { w: 6, h: 7 },
  funnel: { w: 6, h: 7 },
  status_grid: { w: 6, h: 6 },
  // Таблицы и заголовки: во всю ширину — у таблицы своя ширина, в половине
  // ряда она уходит в горизонтальную прокрутку и перестаёт читаться.
  table: { w: 12, h: 7 },
  pivot: { w: 12, h: 7 },
  // Матрица «строка × дата»: столбец на каждый отчёт плюс прирост под
  // значением — в половине ряда она уходит в горизонтальную прокрутку.
  matrix: { w: 12, h: 8 },
  text: { w: 12, h: 2 },
}

/** Тип, которого нет в таблице (новый вид виджета): половина ряда. */
export const FLOW_FALLBACK = { w: 6, h: 6 }

export const ROW_H = 40
export const GAP = 12

export interface FlowItem {
  id: string
  /** Сколько колонок из 12 занимает виджет. */
  span: number
  /** Высота карточки в пикселях; для `auto` — минимальная. */
  height: number
  /**
   * Высота по содержимому, а не по сетке.
   *
   * В свободной сетке высота обязана быть заданной — виджет стоит в клетке.
   * В «потоке» такой необходимости нет, и карточка показателя, обжимающая своё
   * содержимое, экономит на странице из трёх десятков карточек больше тысячи
   * пикселей пустоты. Графикам авто-высота не годится: им высоту надо задать,
   * иначе рисовать будет негде.
   */
  auto: boolean
}

/** Виджеты, чья высота в «потоке» определяется содержимым. */
// Матрица здесь же: у неё столько строк, сколько показателей в форме
// (у госформы — тринадцать), и в фиксированные 8 рядов помещаются две.
// Карточка-таблица с внутренней прокруткой читается хуже длинной страницы.
const AUTO_HEIGHT = new Set(['kpi', 'kpi_group', 'text', 'status_grid', 'image', 'matrix'])

/**
 * Типы, которые на широком мониторе не грех уплотнить, и предел уплотнения.
 * Карточка показателя на 12-колоночной сетке по умолчанию занимает треть ряда
 * (замер 15.08: на четверти ряда имя госформы обрезается до «Колич обращ
 * за…»), но при ширине окна под 1900px четверть ряда — это уже ~460px, и имя
 * помещается целиком. Графики и таблицы не уплотняем: им нужна ширина.
 */
const DENSE_MIN: Record<string, number> = { kpi: 3, kpi_group: 3, gauge: 3, dynamics: 3, image: 3, plan_fact: 4 }

/** Ширина, при которой имя показателя в три строки читается целиком. */
const COMFORT = 330
/** Ниже этой ширины колонка перестаёт вмещать имя показателя. */
const MIN_CARD = 250
/** Ряд из «двух с половиной» карточек выглядит сломанным — только делители 12. */
const DIVISORS = [1, 2, 3, 4, 6, 12]

const cardWidth = (colW: number, span: number, gap: number = GAP): number => colW * span + gap * (span - 1)

/**
 * Место и размер каждого виджета.
 *
 * `width` — фактическая ширина контейнера. На узком экране виджет занимает
 * БОЛЬШЕ колонок, а не меньше: лучше две карточки в ряд, чем три нечитаемых.
 * На широком — наоборот, уплотняется до `DENSE_MIN`, пока карточка остаётся
 * шире `COMFORT`.
 */
export function flowItems(
  widgets: { id: string; widget_type: string }[],
  width: number,
  collapsed?: (id: string) => boolean,
  // Плотность (`lib/density`): ряд и промежуток задаёт читатель. Значения по
  // умолчанию — прежние, поэтому вызов без них ничего не меняет. Параметрами,
  // а не импортом из density: тот берёт «просторные» числа ОТСЮДА, и импорт в
  // обратную сторону замкнул бы модули друг на друга.
  metrics?: { rowH: number; gap: number },
): FlowItem[] {
  const rowH = metrics?.rowH ?? ROW_H
  const gap = metrics?.gap ?? GAP
  const cols = 12
  const colW = width > 0 ? (width - gap * (cols - 1)) / cols : 0
  return widgets.map((w) => {
    const size = FLOW_SIZE[w.widget_type] || FLOW_FALLBACK
    let span = Math.min(cols, size.w)
    if (colW > 0) {
      // тесно — расширяем
      while (span < cols && cardWidth(colW, span, gap) < MIN_CARD) span += 1
      // просторно — уплотняем до предела для этого типа
      const dense = DENSE_MIN[w.widget_type]
      while (dense !== undefined && span > dense && cardWidth(colW, span - 1, gap) >= COMFORT) span -= 1
      if (cols % span !== 0 && span < cols) span = DIVISORS.find((c) => c >= span) ?? cols
    }
    const isCollapsed = collapsed?.(w.id) ?? false
    const h = isCollapsed ? 1 : size.h
    return {
      id: w.id, span,
      height: h * rowH + (h - 1) * gap,
      auto: !isCollapsed && AUTO_HEIGHT.has(w.widget_type),
    }
  })
}
