/**
 * Высота графика под место в карточке — чистый расчёт для `useFitHeight`
 * (WidgetView). Вынесен сюда, потому что внутри хука его нельзя проверить
 * тестом, а ошибка здесь тихая: пустота под графиком или прокрутка в карточке.
 *
 * 🔴 Прежний хук подбирал высоту ИТЕРАЦИЯМИ — «вырос, переполнил, ужался» — и
 * запоминал «потолок» в момент ужатия. Замер 30.09 на «Сравнении показателей»
 * показал, чем это кончается: потолок запоминался в ПЕРЕХОДНЫЙ момент (на миг
 * появилась полоса прокрутки, подписи переносились в лишнюю строку), и график
 * оставался на 60–100px ниже возможного; в других прогонах пересчёт не
 * срабатывал вовсе, и в карточке оставалась прокрутка на 104–119px.
 *
 * Здесь высота считается ПРЯМО: место карточки минус всё, что в ней не график.
 * «Всё, что не график» от высоты графика не зависит, поэтому расчёт сходится за
 * один шаг, и потолок больше не нужен.
 */

/** Запас снизу: без него график «дышит» на пиксель туда-обратно. */
export const FIT_SLACK = 2
/** Меньше этого свободного места — не трогаем: это поля и отступы, а не пустота. */
export const FIT_MIN_FREE = 8

export interface FitMeasure {
  /** Высота, которую карточка отдаёт содержимому (без полей). */
  room: number
  /** Высота всего содержимого — от верха первого блока до низа последнего. */
  content: number
  /** Нынешняя высота самого графика. */
  chart: number
  /** Высота, которую хук держит сейчас. */
  cur: number
  /** Ниже этого графику нельзя. */
  min: number
}

/**
 * Новая высота графика или `null`, если менять нечего.
 *
 * 🔴 Карточка с высотой ПО СОДЕРЖИМОМУ (в ней место всегда равно содержимому)
 * обязана оставаться неподвижной: реши расчёт «ужать на запас» — карточка
 * ужалась бы следом, и график съехал бы до минимума шаг за шагом; реши
 * «вырасти на отступ» — рос бы бесконечно. Поэтому действуем только при
 * настоящем переполнении или заметной пустоте, а не при совпадении с точностью
 * до отступов.
 */
export function fitChartHeight(m: FitMeasure): number | null {
  const over = m.content - m.room
  if (over <= 1 && -over < FIT_MIN_FREE) return null
  const next = Math.max(m.min, Math.floor(m.room - (m.content - m.chart) - FIT_SLACK))
  return Math.abs(next - m.cur) < 2 ? null : next
}
